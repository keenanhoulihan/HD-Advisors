/*
 * Generates the static outline for the "Where I've Been" map on /about.
 * Run once (node scripts/build-map-geometry.mjs) and commit the output, so the
 * site ships one flat SVG path and no map library. Land data: Natural Earth
 * via world-atlas (public domain).
 *
 * The projection is plain equirectangular, so ResumeMap can place any pin
 * from its latitude and longitude with the same linear math:
 *   x = scale * lng(rad) + tx,  y = -scale * lat(rad) + ty
 */
import { readFileSync, writeFileSync } from "node:fs";
import { geoEquirectangular, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const load = (res) =>
  JSON.parse(readFileSync(new URL(`../node_modules/world-atlas/land-${res}.json`, import.meta.url), "utf8"));

const RAD = Math.PI / 180;

/** Fits [west, north, east, south] into a viewBox of the given width. */
function frame([west, north, east, south], width) {
  const scale = width / ((east - west) * RAD);
  const height = Math.round(scale * (north - south) * RAD);
  const tx = -scale * west * RAD;
  const ty = scale * north * RAD;
  return { width, height, scale: +scale.toFixed(4), tx: +tx.toFixed(4), ty: +ty.toFixed(4) };
}

function outline(res, view, precision) {
  const land = feature(load(res), load(res).objects.land);
  const projection = geoEquirectangular()
    .scale(view.scale)
    .translate([view.tx, view.ty])
    .clipExtent([
      [0, 0],
      [view.width, view.height],
    ]);
  const d = geoPath(projection).digits(precision)(land) ?? "";
  // Drop specks: islands smaller than a pin would only add noise.
  return d
    .split("M")
    .filter(Boolean)
    .filter((ring) => ring.split(/[LZ]/).length > 6)
    .map((ring) => `M${ring}`)
    .join("");
}

// The Americas, from just above Chicago to Tierra del Fuego.
const AMERICAS = [-126, 52, -32, -56];
// Mid-Atlantic inset: Washington DC, Charlottesville, and Williamsburg sit too close to tell apart at full scale.
const MID_ATLANTIC = [-80, 39.6, -75.6, 36.6];

const map = frame(AMERICAS, 600);
const inset = frame(MID_ATLANTIC, 240);

const out = `/* Generated by scripts/build-map-geometry.mjs. Do not edit by hand. */

export type MapFrame = {
  width: number;
  height: number;
  scale: number;
  tx: number;
  ty: number;
  /** [west, north, east, south] in degrees. */
  bounds: readonly [number, number, number, number];
  path: string;
};

export const AMERICAS_MAP: MapFrame = ${JSON.stringify({ ...map, bounds: AMERICAS, path: outline("110m", map, 1) })};

export const MID_ATLANTIC_INSET: MapFrame = ${JSON.stringify({ ...inset, bounds: MID_ATLANTIC, path: outline("50m", inset, 1) })};
`;

writeFileSync(new URL("../src/lib/map-geometry.ts", import.meta.url), out);
console.log(`map ${map.width}x${map.height}, inset ${inset.width}x${inset.height}, ${(out.length / 1024).toFixed(1)} KB`);
